"""Sync per-model results/metrics.csv from the canonical comparison.csv.

The comparison.csv is the canonical source (generated by run_comparison.py with
genuine group-CV). Per-model results folders should match it exactly to avoid
contradictory duplicate documentation.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path("A:/Projects/ToS-risk-flagging")
MODEL_MAP = {
    "naive_bayes": "multinomial_nb",
    "logistic_regression": "logistic_regression",
    "svm/linear": "linear_svm",
    "svm/rbf": "rbf_svm",
    "decision_tree": "decision_tree",
    "random_forest": "random_forest",
    "knn": "knn",
    "gradient_boosting": "gradient_boosting",
}
PROTOCOLS = ["primary", "clause"]

def main():
    for protocol in PROTOCOLS:
        comp = pd.read_csv(
            ROOT / "results" / "comparison" / protocol / "comparison.csv"
        )
        for folder, csv_name in MODEL_MAP.items():
            mrow = comp[comp["model"] == csv_name]
            if mrow.empty:
                print(f"SKIP: {csv_name} not in {protocol} comparison")
                continue
            mrow = mrow.iloc[0]

            out_dir = ROOT / "models" / folder / "results" / protocol
            out_dir.mkdir(parents=True, exist_ok=True)

            # Write metrics.csv from canonical comparison row (all columns).
            mrow.to_frame().T.to_csv(out_dir / "metrics.csv", index=False)

            # Copy confusion matrix from canonical comparison output.
            src_cm = ROOT / "results" / "comparison" / protocol / f"{csv_name}_confusion_matrix.csv"
            if src_cm.exists():
                import shutil
                shutil.copy2(src_cm, out_dir / "confusion_matrix.csv")

            print(f"Synced {folder}/{protocol}/metrics.csv + confusion_matrix.csv")

    print("Done. Per-model results now match canonical comparison.csv")


if __name__ == "__main__":
    main()
